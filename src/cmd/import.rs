use clap::{ArgAction, Parser};
use crossterm::style::Stylize;
use std::path::PathBuf;

use super::install;
use crate::Result;

/// Import apps from an export file (or stdin) and install them
#[derive(Debug, Parser)]
pub struct Args {
    /// Export file to read (defaults to stdin)
    file: Option<PathBuf>,
    /// Assume yes to all prompts and run non-interactively
    #[arg(short = 'y', long, action = ArgAction::SetTrue)]
    assume_yes: bool,
    /// Target architecture for all imported apps (overrides per-app export)
    #[arg(long)]
    arch: Option<String>,
}

pub fn execute(args: Args, session: &scoop_rs::Session) -> Result<()> {
    let input = match &args.file {
        Some(path) => std::fs::read_to_string(path)?,
        None => {
            let mut input = String::new();
            std::io::Read::read_to_string(&mut std::io::stdin(), &mut input)?;
            input
        }
    };

    let (buckets, apps) = parse_export(&input)?;
    if apps.is_empty() {
        println!("Nothing to import.");
        return Ok(());
    }

    // Upstream `scoop import` adds missing buckets first.
    if !buckets.is_empty() {
        let existing: Vec<String> = scoop_rs::operation::bucket_list(session)?
            .iter()
            .map(|b| b.name().to_owned())
            .collect();
        for bucket in &buckets {
            if existing
                .iter()
                .any(|e| e.eq_ignore_ascii_case(&bucket.name))
            {
                continue;
            }
            if bucket.source.is_empty() {
                eprintln!(
                    "warning: bucket '{}' has no source URL; skipping",
                    bucket.name
                );
                continue;
            }
            println!("Adding bucket {}...", bucket.name);
            if let Err(e) = scoop_rs::operation::bucket_add(session, &bucket.name, &bucket.source) {
                eprintln!("warning: could not add bucket '{}': {e}", bucket.name);
            }
        }
    }

    // Upstream exports record apps installed from a locally generated
    // manifest as `Source: "<auto-generated>"`. Those have no bucket
    // manifest, so they must be reinstalled as `app@version` (which
    // regenerates the manifest from bucket history or autoupdate) rather
    // than as `<auto-generated>/app`, which resolves to nothing.
    let auto_generated = apps.iter().any(|app| app.bucket == AUTO_GENERATED_SOURCE);
    let installed_names: Vec<String> = if auto_generated {
        scoop_rs::operation::package_query(session, vec!["*"], vec![], true)?
            .iter()
            .map(|p| p.name().to_ascii_lowercase())
            .collect()
    } else {
        vec![]
    };

    let mut queries = vec![];
    let mut held = vec![];
    let mut skipped = vec![];
    let mut already_installed = vec![];

    for app in &apps {
        if app.name.is_empty() {
            continue;
        }

        let name = app.name.as_str();

        // Per-app architecture from the export, unless globally overridden.
        let arch = match args.arch.as_deref() {
            Some(arch) => Some(arch.to_owned()),
            None => app.arch.clone(),
        };

        let query = match plan_query(app, installed_names.contains(&name.to_ascii_lowercase())) {
            QueryPlan::Install(query) => query,
            QueryPlan::AlreadyInstalled => {
                already_installed.push(name.to_owned());
                continue;
            }
            QueryPlan::Skip => {
                skipped.push(name.to_owned());
                continue;
            }
        };
        queries.push((arch, query));

        if app.held {
            held.push(name.to_owned());
        }
    }

    if !already_installed.is_empty() {
        println!(
            "{} {}",
            "Already installed, skipping:".dark_grey(),
            already_installed.join(", ")
        );
    }

    if !skipped.is_empty() {
        println!(
            "{} {}",
            "Skipping isolated apps (no bucket manifest):".yellow(),
            skipped.join(", ")
        );
    }

    if queries.is_empty() {
        println!("Nothing installable to import.");
        return Ok(());
    }

    println!("Importing {} app(s).", queries.len());

    // Group by architecture: the resolution override is process-wide, so
    // each arch group installs in its own transaction.
    queries.sort_by(|a, b| a.0.cmp(&b.0));
    let mut idx = 0;
    while idx < queries.len() {
        let arch = queries[idx].0.clone();
        let mut end = idx;
        while end < queries.len() && queries[end].0 == arch {
            end += 1;
        }
        let group: Vec<String> = queries[idx..end]
            .iter()
            .map(|(_, query)| query.clone())
            .collect();

        install::execute(
            install::Args::from_packages(group, args.assume_yes, arch),
            session,
        )?;
        idx = end;
    }
    // The resolution override is process-wide: never leak it past import.
    scoop_rs::arch::clear_override();

    // Restore held states recorded in the export.
    for name in &held {
        if let Err(e) = scoop_rs::operation::package_hold(session, name, true) {
            eprintln!("Could not re-hold '{}': {}", name, e);
        }
    }

    Ok(())
}

/// Source marker upstream `scoop export` writes for apps installed from a
/// locally generated manifest (`scoop install app@version`, or a manifest
/// that was auto-generated from git history). There is no bucket manifest
/// to resolve by name for these.
const AUTO_GENERATED_SOURCE: &str = "<auto-generated>";

/// Whether an export `Source` is a manifest reference rather than a bucket
/// name: a URL, a UNC path, or a local `.json` file.
fn is_manifest_source(source: &str) -> bool {
    source.contains("://")
        || source.starts_with("\\\\")
        || source.to_ascii_lowercase().ends_with(".json")
}

/// What to do with a single export entry.
#[derive(Clone, Debug, PartialEq, Eq)]
enum QueryPlan {
    /// Resolve and install from this query.
    Install(String),
    /// The app is installed already; a pinned reinstall would downgrade it.
    AlreadyInstalled,
    /// Nothing to reinstall from (no bucket manifest and no version).
    Skip,
}

/// Decide how a single export entry is imported.
///
/// Upstream `scoop export` writes `Source: "<auto-generated>"` for apps
/// installed from a locally generated manifest. Those have no bucket
/// manifest, so they are reinstalled as `app@version` (which regenerates
/// the manifest from bucket history or autoupdate) instead of the bogus
/// `<auto-generated>/app` query. Isolated apps record their manifest URL or
/// path as the source, which installs directly.
fn plan_query(app: &ExportApp, is_installed: bool) -> QueryPlan {
    let name = app.name.as_str();
    let bucket = app.bucket.as_str();

    // Isolated apps have no bucket manifest to reinstall from.
    if bucket == "__isolated__" {
        return QueryPlan::Skip;
    }

    if bucket == AUTO_GENERATED_SOURCE {
        if is_installed {
            return QueryPlan::AlreadyInstalled;
        }

        // Without a version there is nothing to regenerate from.
        return match app.version.is_empty() {
            true => QueryPlan::Skip,
            false => QueryPlan::Install(format!("{name}@{}", app.version)),
        };
    }

    if is_manifest_source(bucket) {
        return QueryPlan::Install(bucket.to_owned());
    }

    match bucket.is_empty() {
        true => QueryPlan::Install(name.to_owned()),
        false => QueryPlan::Install(format!("{bucket}/{name}")),
    }
}

/// A bucket entry from an export file.
#[derive(Clone, Debug, PartialEq, Eq)]
struct ExportBucket {
    name: String,
    source: String,
}

/// An app entry from an export file.
#[derive(Clone, Debug, PartialEq, Eq)]
struct ExportApp {
    name: String,
    version: String,
    bucket: String,
    arch: Option<String>,
    held: bool,
}

/// Read a string field under any of several key spellings (upstream
/// PascalCase or bagger lowercase).
fn str_field(obj: &serde_json::Map<String, serde_json::Value>, keys: &[&str]) -> String {
    keys.iter()
        .filter_map(|k| obj.get(*k)?.as_str())
        .next()
        .unwrap_or("")
        .to_owned()
}

/// Parse an export file in either shape: upstream's
/// `{"buckets": [...], "apps": [...]}` object or bagger's legacy bare
/// array. Unknown keys are ignored; entries without names are skipped.
fn parse_export(input: &str) -> Result<(Vec<ExportBucket>, Vec<ExportApp>)> {
    let value: serde_json::Value = serde_json::from_str(input)?;
    let (buckets_value, apps_value) = match &value {
        serde_json::Value::Object(map) => (
            map.get("buckets").or(map.get("Buckets")),
            map.get("apps")
                .or(map.get("Apps"))
                .cloned()
                .unwrap_or(serde_json::Value::Array(vec![])),
        ),
        serde_json::Value::Array(_) => (None, value.clone()),
        _ => {
            return Err(anyhow::anyhow!(
                "export file must contain an app list (array, or {{\"buckets\", \"apps\"}} object)"
            ))
        }
    };

    let mut buckets = Vec::new();
    if let Some(list) = buckets_value.and_then(|v| v.as_array()) {
        for entry in list {
            let Some(obj) = entry.as_object() else {
                continue;
            };
            let name = str_field(obj, &["name", "Name", "bucket"]);
            if name.is_empty() || name == "__isolated__" {
                continue;
            }
            buckets.push(ExportBucket {
                name,
                source: str_field(obj, &["source", "Source", "url", "URL"]),
            });
        }
    }

    let mut apps = Vec::new();
    let list = apps_value.as_array().ok_or_else(|| {
        anyhow::anyhow!(
            "export file must contain an app list (array, or {{\"buckets\", \"apps\"}} object)"
        )
    })?;
    for entry in list {
        let Some(obj) = entry.as_object() else {
            continue;
        };
        let name = str_field(obj, &["Name", "name"]);
        if name.is_empty() {
            continue;
        }
        let arch = str_field(obj, &["architecture", "Architecture"]);
        apps.push(ExportApp {
            name,
            version: str_field(obj, &["Version", "version"]),
            bucket: str_field(obj, &["Source", "source", "bucket"]),
            arch: (!arch.is_empty()).then_some(arch),
            held: obj
                .get("held")
                .or(obj.get("Held"))
                .and_then(|v| v.as_bool())
                .unwrap_or(false),
        });
    }

    Ok((buckets, apps))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Upstream `scoop export` shape (PascalCase object) parses, including
    /// the bucket list for auto-adding.
    #[test]
    fn parses_upstream_export_shape() {
        let input = r#"{
            "buckets": [{"Name": "extras", "Source": "https://github.com/ScoopInstaller/Extras"}],
            "apps": [
                {"Name": "bat", "Version": "0.26.1", "Source": "extras", "Updated": "2026-01-01", "Info": ""},
                {"Name": "", "Source": "main"}
            ]
        }"#;
        let (buckets, apps) = parse_export(input).unwrap();
        assert_eq!(
            buckets,
            vec![ExportBucket {
                name: "extras".to_owned(),
                source: "https://github.com/ScoopInstaller/Extras".to_owned(),
            }]
        );
        assert_eq!(apps.len(), 1);
        assert_eq!(apps[0].name, "bat");
        assert_eq!(apps[0].version, "0.26.1");
        assert_eq!(apps[0].bucket, "extras");
        assert_eq!(apps[0].arch, None);
        assert!(!apps[0].held);
    }

    /// Bagger's own shape (bare array, lowercase + extensions) parses.
    #[test]
    fn parses_legacy_array_shape() {
        let input = r#"[
            {"name": "zstd", "bucket": "main", "version": "1.5.7", "architecture": "64bit", "held": true},
            {"name": "lonely", "bucket": "__isolated__", "version": "1.0", "architecture": "", "held": false}
        ]"#;
        let (buckets, apps) = parse_export(input).unwrap();
        assert!(buckets.is_empty());
        assert_eq!(apps.len(), 2);
        assert_eq!(apps[0].arch, Some("64bit".to_owned()));
        assert!(apps[0].held);
        // The isolated marker survives parsing (the installer skips it).
        assert_eq!(apps[1].bucket, "__isolated__");
    }

    #[test]
    fn rejects_non_list_exports() {
        assert!(parse_export("{}").unwrap().1.is_empty());
        assert!(parse_export("42").is_err());
    }

    fn app(name: &str, version: &str, bucket: &str) -> ExportApp {
        ExportApp {
            name: name.to_owned(),
            version: version.to_owned(),
            bucket: bucket.to_owned(),
            arch: None,
            held: false,
        }
    }

    /// Upstream `<auto-generated>` sources must not become the bogus
    /// `<auto-generated>/name` query that aborted the whole import.
    #[test]
    fn auto_generated_source_pins_the_exported_version() {
        let entry = app("opencode", "1.17.20", "<auto-generated>");
        assert_eq!(
            plan_query(&entry, false),
            QueryPlan::Install("opencode@1.17.20".to_owned())
        );
        // Already installed: a pinned reinstall would downgrade it.
        assert_eq!(plan_query(&entry, true), QueryPlan::AlreadyInstalled);
        // No version to regenerate from.
        assert_eq!(
            plan_query(&app("opencode", "", "<auto-generated>"), false),
            QueryPlan::Skip
        );
    }

    /// Bucket sources keep the `bucket/app` form, empty sources fall back
    /// to the bare name, and manifest sources install directly.
    #[test]
    fn plans_bucket_and_manifest_sources() {
        assert_eq!(
            plan_query(&app("bat", "0.26.1", "extras"), false),
            QueryPlan::Install("extras/bat".to_owned())
        );
        assert_eq!(
            plan_query(&app("bat", "0.26.1", ""), false),
            QueryPlan::Install("bat".to_owned())
        );
        assert_eq!(
            plan_query(&app("x", "1.0", "https://example.com/x.json"), false),
            QueryPlan::Install("https://example.com/x.json".to_owned())
        );
        assert_eq!(
            plan_query(&app("x", "1.0", r"C:\manifests\x.json"), false),
            QueryPlan::Install(r"C:\manifests\x.json".to_owned())
        );
        assert_eq!(
            plan_query(&app("x", "1.0", "__isolated__"), false),
            QueryPlan::Skip
        );
    }
}
